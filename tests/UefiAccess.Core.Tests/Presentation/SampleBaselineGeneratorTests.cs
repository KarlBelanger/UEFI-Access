/// <summary>
/// The sample baseline folder committed under tools/sample-baseline: a folder
/// <see cref="BaselineExporter"/> writes from the test fixtures (the four Boot#### load options,
/// BootOrder, BootNext, Timeout, SecureBoot, SetupMode, PK, KEK, db, dbx) with a fixed timestamp
/// and an identity that reads "Sample (fixtures)" in every field, and since M4 the ten agreed Dell
/// BIOS settings of the A18 fixture as dell-settings.json, so the tester can
/// walk every screen of the application, the Dell settings region included, on any PC without Dell
/// software, and nobody mistakes it for a real machine. The folder is
/// generated by this class only when the environment variable
/// <see cref="EnvironmentVariable"/> is "1"; on every other run the tests assert that the
/// committed folder is exactly what the exporter produces today and loads through
/// <see cref="BaselineFolderSource"/> and the shell with zero warnings, so a fixture, decoder or
/// exporter change that would silently change the sample fails here and says how to regenerate.
/// </summary>
public sealed class SampleBaselineGeneratorTests
{
    /// <summary>Set to "1" to (re)write tools/sample-baseline instead of verifying it.</summary>
    public const string EnvironmentVariable = "UEFIACCESS_WRITE_SAMPLE_BASELINE";

    /// <summary>The folder name under tools/.</summary>
    public const string FolderName = "sample-baseline";

    /// <summary>The text every identity field carries.</summary>
    public const string SampleText = "Sample (fixtures)";

    /// <summary>The fixed export time as index.json records it locally (UTC, so the offset is zero).</summary>
    public const string LocalTimestampText = "2026-09-15T12:00:00+00:00";

    /// <summary>The tool version written into index.json; fixed so a rebuild on another commit changes nothing.</summary>
    public const string SampleToolVersion = "0.1.0+sample-fixtures";

    /// <summary>The number of variables in the sample.</summary>
    public const int VariableCount = 13;

    private const string NotInspected = "Sample baseline generated from the test fixtures: nothing on this machine was inspected.";

    private static readonly DateTimeOffset Timestamp = new(2026, 9, 15, 12, 0, 0, TimeSpan.Zero);

    private static readonly string LogText = string.Join(
        "\n",
        "Sample baseline generated from the UefiAccess test fixtures by tests/UefiAccess.Core.Tests/Presentation/SampleBaselineGeneratorTests.cs.",
        "Not a real machine: the identity reads \"" + SampleText + "\" in every field, the timestamp is fixed at " + LocalTimestampText + ",",
        "and the Secure Boot keys are deterministic byte patterns, not certificates; dell-settings.json holds the Dell",
        "fixtures' values of BIOS A18, read from no machine. It exists so the application's",
        "Open baseline folder can be exercised on any PC; it proves nothing about any hardware.",
        "Regenerate after a fixture change with: " + EnvironmentVariable + "=1 dotnet test UefiAccess.sln -c Release",
        string.Empty);

    /// <summary>The committed folder.</summary>
    public static string Folder => Path.Combine(RepositoryPaths.Root, "tools", FolderName);

    [Fact]
    public async Task SampleBaseline_IsWrittenOnlyWhenAsked_AndAlwaysMatchesTheExporterAndLoadsWithZeroWarnings()
    {
        BaselineRequest request = Request();
        if (string.Equals(Environment.GetEnvironmentVariable(EnvironmentVariable), "1", StringComparison.Ordinal))
        {
            Write(request);
        }

        Assert.True(Directory.Exists(Folder), Folder + " is missing; run the tests once with " + EnvironmentVariable + "=1 to generate it");
        Assert.True(File.Exists(Path.Combine(Folder, BaselineExporter.IndexFileName)));
        Assert.True(File.Exists(Path.Combine(Folder, BaselineExporter.DecodedFileName)));
        Assert.True(File.Exists(Path.Combine(Folder, BaselineExporter.PlatformFileName)));
        Assert.True(File.Exists(Path.Combine(Folder, BaselineExporter.LogFileName)));
        Assert.True(File.Exists(Path.Combine(Folder, BaselineExporter.DellSettingsFileName)));
        Assert.Equal(VariableCount, Directory.GetFiles(Path.Combine(Folder, BaselineExporter.VariablesDirectoryName), "*" + BaselineExporter.VariableFileExtension).Length);

        // The committed text files are byte-for-byte (line endings aside) what the exporter
        // produces from today's fixtures, decoders and identity: any drift asks for a regeneration.
        AssertFileEquals(BaselineExporter.IndexFileName, JsonSerializer.Serialize(BaselineExporter.BuildIndex(request), BaselineExporter.JsonOptions));
        AssertFileEquals(BaselineExporter.DecodedFileName, JsonSerializer.Serialize(request.Decoded, BaselineExporter.JsonOptions));
        AssertFileEquals(BaselineExporter.PlatformFileName, JsonSerializer.Serialize(request.Platform, BaselineExporter.JsonOptions));
        AssertFileEquals(BaselineExporter.DellSettingsFileName, JsonSerializer.Serialize(request.DellSettings, BaselineExporter.JsonOptions));
        Assert.Contains(BaselineExporter.DellSettingsFileName, File.ReadAllText(Path.Combine(Folder, BaselineExporter.LogFileName)), StringComparison.Ordinal);
        Assert.StartsWith(Normalize(LogText), Normalize(File.ReadAllText(Path.Combine(Folder, BaselineExporter.LogFileName))), StringComparison.Ordinal);
        Assert.Contains(BaselineExporter.LogOutcomeHeader, File.ReadAllText(Path.Combine(Folder, BaselineExporter.LogFileName)), StringComparison.Ordinal);
        Assert.Contains("Errors: 0", File.ReadAllText(Path.Combine(Folder, BaselineExporter.LogFileName)), StringComparison.Ordinal);

        // The folder loads through the source the application uses, with nothing skipped.
        SourceResult result = await new BaselineFolderSource(Folder).LoadAsync(CancellationToken.None);

        Assert.Equal(SourceStatus.Loaded, result.Status);
        Assert.Empty(result.Warnings);
        Assert.Null(result.Message);
        Assert.True(result.IsOffline);
        Assert.Equal(FirmwareType.Uefi, result.FirmwareType);
        Assert.Equal(EnumerationMethod.InMemory, result.Method);
        Assert.Equal(Strings.BaselinePrefix + Folder + " (" + LocalTimestampText + ")", result.SourceDescription);
        Assert.Equal(VariableCount, result.Variables.Count);
        Assert.NotNull(result.Identity);
        Assert.Equal(SampleText, result.Identity.Manufacturer);
        Assert.Equal(SampleText, result.Identity.Model);
        Assert.Equal(SampleText, result.Identity.BiosVersion);
        Assert.Equal(SampleText, result.Identity.ServiceTag);
        Assert.Equal(SampleText, result.Identity.Cpu);
        Assert.Equal(SampleText, result.Identity.OsCaption);
        Assert.False(result.Identity.ExpectedModelConfirmed);

        VariableSet loaded = new(result.Variables);
        foreach (FirmwareVariable original in request.Variables)
        {
            FirmwareVariable? found = loaded.Find(original.Name, original.VendorGuid);
            Assert.NotNull(found);
            Assert.Equal(original.Attributes, found.Attributes);
            Assert.Equal(original.Data, found.Data);
        }

        Assert.Equal(
            new[] { "Boot0001", "Boot0002", "Boot0003", "Boot0004", "BootNext", "BootOrder", "KEK", "PK", "SecureBoot", "SetupMode", "Timeout", "db", "dbx" },
            result.Variables.Select(variable => variable.Name).ToArray());

        // The Dell BIOS settings: the ten agreed rows with the A18 values, recorded at the sample's
        // time from Dell Command Monitor on a machine that reads "Sample (fixtures)".
        Assert.Equal(FolderName, result.BaselineFolderName);
        Assert.NotNull(result.DellBaseline);
        Assert.True(result.DellBaseline.Present);
        Assert.Null(result.DellBaseline.Problem);
        DellSettingsResult dell = Assert.IsType<DellSettingsResult>(result.DellBaseline.Settings);
        Assert.Equal(DellReadOutcome.Complete, dell.Outcome);
        Assert.Equal(DellSettingsSource.DellCommandMonitor, dell.Source);
        Assert.Equal(Timestamp, dell.ReadAt);
        Assert.Equal(new DellMachine(SampleText, SampleText, SampleText), dell.Machine);
        Assert.Empty(dell.Problems);
        Assert.Equal(DellAttributeCatalog.Default.Select(entry => entry.Id), dell.Settings.Select(setting => setting.Id));
        Assert.Equal(DcmRowFixtures.UnitA18Texts, dell.Settings.Select(DellSentences.ValueText));
    }

    [Fact]
    public async Task SampleBaseline_LoadsThroughTheShell_WithTheSampleIdentityInTheStripAndTheTitle()
    {
        Assert.True(Directory.Exists(Folder), Folder + " is missing; run the tests once with " + EnvironmentVariable + "=1 to generate it");
        RecordingAnnouncer announcer = new();
        RecordingFocusSink focus = new();
        ShellViewModel shell = new(
            new NeverSource(),
            folder => new BaselineFolderSource(folder),
            announcer,
            focus,
            new NullPlatformInteractions());
        shell.AnnounceReady();

        await shell.OpenBaselineAsync(Folder);

        Assert.Equal(ShellState.Loaded, shell.State);
        Assert.True(shell.IsOffline);
        Assert.Equal("UefiAccess – Baseline (offline): " + Folder + " (" + LocalTimestampText + ")", shell.WindowTitle);
        Assert.Equal("Loaded 13 variables from Baseline (offline): " + Folder + " (" + LocalTimestampText + ") (InMemory)", shell.StatusText);
        Assert.Equal(new[] { FocusTarget.ListFirstRow }, focus.Requests);
        Assert.Equal(VariableCount, shell.List.TotalCount);
        Assert.Equal("Manufacturer: " + SampleText, shell.Manufacturer);
        Assert.Equal("Model: " + SampleText, shell.Model);
        Assert.Equal("BIOS version: " + SampleText, shell.BiosVersion);
        Assert.Equal("Service tag: " + SampleText, shell.ServiceTag);
        Assert.Equal("CPU: " + SampleText, shell.Cpu);
        Assert.Equal("Operating system: " + SampleText, shell.OperatingSystem);
        Assert.Equal("Expected model confirmed: No", shell.ExpectedModelText);

        // The one WARN line is the identity's own note (the expected model is not confirmed, on
        // purpose); no variable was skipped.
        LogLineViewModel warning = Assert.Single(shell.Log.Lines, line => line.Level == LogViewModel.WarnLevel);
        Assert.Equal(Identity().ExpectedModelNotes, warning.Message);
        Assert.DoesNotContain(shell.Log.Lines, line => line.Level == LogViewModel.ErrorLevel);

        // The fixtures decode the way they do everywhere else: the boot entries are load options
        // with their descriptions, the Secure Boot keys are signature lists.
        VariableItemViewModel boot0001 = shell.List.AllItems.Single(item => item.Name == "Boot0001");
        Assert.Equal("LoadOption", boot0001.Kind);
        Assert.Contains("Windows Boot Manager", boot0001.Summary, StringComparison.Ordinal);
        Assert.Equal("BootOrder", shell.List.AllItems.Single(item => item.Name == "BootOrder").Kind);
        Assert.NotEqual(Strings.RawKind, shell.List.AllItems.Single(item => item.Name == "dbx").Kind);
        Assert.Contains(shell.List.Groups, group => group.Label == NamespaceCatalog.EfiGlobalVariableLabel);
    }

    [Fact]
    public async Task SampleBaseline_ShowsTheTenDellRowsOffline_WithZeroWarnings()
    {
        Assert.True(Directory.Exists(Folder), Folder + " is missing; run the tests once with " + EnvironmentVariable + "=1 to generate it");
        RecordingAnnouncer announcer = new();
        RecordingFocusSink focus = new();
        NeverDellSource dellSource = new();
        ShellViewModel shell = new(
            new NeverSource(),
            folder => new BaselineFolderSource(folder),
            announcer,
            focus,
            new NullPlatformInteractions(),
            dellSource: dellSource);
        shell.AnnounceReady();

        await shell.OpenBaselineAsync(Folder);

        // The load's sentence only, and the Dell rows in Baseline mode.
        Assert.Equal(new[] { Strings.IdleStatus, Strings.LoadingStatus, "Loaded 13 variables from Baseline (offline): " + Folder + " (" + LocalTimestampText + ") (InMemory)" }, announcer.History);
        Assert.Equal(DellViewMode.Baseline, shell.Dell.Mode);
        Assert.Equal(DellAttributeCatalog.Default.Select(entry => entry.DisplayName), shell.Dell.Rows.Select(row => row.DisplayName));
        Assert.Equal(DcmRowFixtures.UnitA18Texts, shell.Dell.Rows.Select(row => row.CurrentText));
        Assert.Equal("Wake on LAN: Disabled. Possible values: Disabled, LAN Only, LAN with PXE Boot.", shell.Dell.Rows[8].AccessibleName);
        Assert.Equal(
            "Recorded at 15 September 2026 12:00 UTC from Dell Command Monitor in baseline folder sample-baseline, BIOS Sample (fixtures). Offline: nothing is loaded from this computer.",
            shell.Dell.StateText);
        shell.OnRegionArrived(Region.Dell);
        Assert.Equal("Dell settings region, from baseline folder sample-baseline", shell.StatusText);

        // Zero warnings: the one WARN line is the identity's own note, as before; nothing of this PC was read.
        LogLineViewModel warning = Assert.Single(shell.Log.Lines, line => line.Level == LogViewModel.WarnLevel);
        Assert.Equal(Identity().ExpectedModelNotes, warning.Message);
        Assert.Equal(0, dellSource.ReadCalls);

        // Alt+S says that a baseline folder is shown, and reads nothing.
        await shell.ReadDellSettingsAsync();
        Assert.Equal(Strings.DellBaselineShownStatus, shell.StatusText);
        Assert.Equal(0, dellSource.ReadCalls);
    }

    /// <summary>The exact request the committed folder was written from.</summary>
    private static BaselineRequest Request()
    {
        IReadOnlyList<FirmwareVariable> variables = Variables();
        VariableSet set = new(variables);
        MachineIdentityResult identity = Identity();
        IReadOnlyList<DecodedVariable> decoded = DecoderRegistry.CreateDefault().DecodeAll(set);
        PlatformSnapshot platform = new(
            identity,
            new TpmInfoResult(false, null, null, null, new[] { NotInspected }),
            new SecureBootPolicyResult(null, true, false, null, null, null, true, true, new[] { NotInspected + " SecureBoot and SetupMode come from the sample variables." }),
            new BitLockerResult(Array.Empty<BitLockerVolume>(), new[] { NotInspected }),
            new DellInterfaceProbeResult(false, Array.Empty<string>(), Array.Empty<DellAttributeSample>(), false, null, null, null, false, false, new[] { NotInspected }));

        return new BaselineRequest(
            Path.Combine(RepositoryPaths.Root, "tools"),
            FolderName,
            variables,
            FirmwareType.Uefi,
            PrivilegeState.Enabled,
            identity,
            decoded,
            platform,
            LogText,
            SampleToolVersion,
            Timestamp)
        {
            DellSettings = DellSettingsFile.ToDocument(DellSettings()),
        };
    }

    /// <summary>
    /// The sample's Dell BIOS settings: Dell Command Monitor's answer
    /// over the 72 rows of the A18 export fixture (<see cref="DcmRowFixtures.UnitA18"/>), made by the
    /// provider's and the reader's own pure functions, outcome Complete, read at the sample's fixed
    /// time, on a machine whose three fields read <see cref="SampleText"/> like every identity field
    /// of the sample. Nothing of any machine is read.
    /// </summary>
    private static DellSettingsResult DellSettings()
    {
        DellSettingsResult read = CliTestHarness.DellCompleteA18(DellReadOptions.Default);
        Assert.Equal(DellReadOutcome.Complete, read.Outcome);
        return read with { ReadAt = Timestamp, ElapsedMs = 0, Machine = new DellMachine(SampleText, SampleText, SampleText) };
    }

    /// <summary>
    /// The sample variables, all from the shared fixtures: Boot0001 Windows Boot Manager, Boot0002
    /// PXE, Boot0003 a USB stick, Boot0004 a legacy BBS disk, BootOrder (1, 3, 2), BootNext (3),
    /// Timeout (2 s), SecureBoot on, SetupMode off, and PK, KEK, db and dbx as signature lists.
    /// </summary>
    private static IReadOnlyList<FirmwareVariable> Variables()
    {
        return new[]
        {
            Boot0001(),
            Boot0002(),
            Boot0003(),
            Boot0004(),
            BootOrder(),
            Global("BootNext", U16(3)),
            Global("Timeout", U16(2)),
            Global("SecureBoot", new byte[] { 1 }, BsRt),
            Global("SetupMode", new byte[] { 0 }, BsRt),
            Global("PK", SignatureListFixtures.X509List(200), NvBsRtTa),
            Global("KEK", Concat(SignatureListFixtures.X509List(150), SignatureListFixtures.X509List(160)), NvBsRtTa),
            Security("db", Concat(SignatureListFixtures.X509List(120), SignatureListFixtures.Sha256List(3))),
            Security("dbx", SignatureListFixtures.Sha256List(3)),
        };
    }

    private static MachineIdentityResult Identity() => new(
        SampleText,
        SampleText,
        SampleText,
        SampleText,
        SampleText,
        SampleText,
        SampleText,
        SampleText,
        SampleText,
        null,
        null,
        false,
        "Sample baseline generated from the UefiAccess test fixtures; not a real machine, so the expected model is not confirmed.",
        Array.Empty<string>());

    private static void Write(BaselineRequest request)
    {
        if (Directory.Exists(Folder))
        {
            Directory.Delete(Folder, recursive: true);
        }

        BaselineExportResult result = new BaselineExporter().Export(request);
        Assert.Empty(result.Errors);
        Assert.Equal(Path.GetFullPath(Folder), result.Directory);
        Assert.Equal(VariableCount, result.VariableCount);
    }

    private static void AssertFileEquals(string fileName, string expected)
    {
        string actual = File.ReadAllText(Path.Combine(Folder, fileName));
        Assert.True(
            string.Equals(Normalize(expected), Normalize(actual), StringComparison.Ordinal),
            "tools/" + FolderName + "/" + fileName + " differs from what the exporter produces now; regenerate it with " + EnvironmentVariable + "=1 dotnet test UefiAccess.sln -c Release and commit the folder");
    }

    private static string Normalize(string text) => text.Replace("\r\n", "\n", StringComparison.Ordinal);

    /// <summary>A live source the shell must not touch in these tests.</summary>
    private sealed class NeverSource : IVariableSource
    {
        public string Description => Strings.LiveSourceName;

        public bool IsOffline => false;

        public Task<SourceResult> LoadAsync(CancellationToken cancellationToken) => throw new InvalidOperationException("the live source must not be used");
    }

    /// <summary>A Dell settings source the shell must not read in these tests; it counts the reads it was asked for.</summary>
    private sealed class NeverDellSource : IDellSettingsSource
    {
        public int ReadCalls { get; private set; }

        public Task<DellSettingsResult> ReadAsync()
        {
            ReadCalls++;
            return Task.FromException<DellSettingsResult>(new InvalidOperationException("the Dell settings must not be read"));
        }
    }
}
