using System.Windows.Threading;
using Serilog;
using UefiAccess.Presentation.Accessibility;

namespace UefiAccess.App.Platform;

/// <summary>
/// The WPF <see cref="IFocusSink"/>: hands every focus request to the main window, which maps
/// the <see cref="FocusTarget"/> to a control (the first or selected list row through the item
/// container generator, the filter box, the Status box, the first detail field, the first
/// toolbar button, the log list, and for the change flows of M3 the selected row of the boot order
/// list, the Change button that opened the Confirm change dialog, and the written variable's row
/// after the live reload) and calls <c>Keyboard.Focus</c> on it. The request is queued
/// with <see cref="Dispatcher.BeginInvoke(DispatcherPriority, Delegate)"/> at
/// <see cref="DispatcherPriority.Loaded"/> so that item containers generated by the pending
/// layout pass exist when the focus moves; this is a one-off deferral to the end of the current
/// dispatcher cycle, not a timer. Never throws.
/// </summary>
public sealed class WpfFocusSink : IFocusSink
{
    private readonly MainWindow _window;
    private readonly ILogger _logger;

    /// <summary>Creates the sink over the main window.</summary>
    /// <param name="window">The window that owns the controls.</param>
    /// <param name="logger">Optional logger; null disables logging.</param>
    /// <exception cref="ArgumentNullException"><paramref name="window"/> is null.</exception>
    public WpfFocusSink(MainWindow window, ILogger? logger = null)
    {
        ArgumentNullException.ThrowIfNull(window);
        _window = window;
        _logger = logger ?? Serilog.Core.Logger.None;
    }

    /// <inheritdoc />
    public void RequestFocus(FocusTarget target)
    {
        if (target == FocusTarget.None)
        {
            return;
        }

        try
        {
            _window.Dispatcher.BeginInvoke(DispatcherPriority.Loaded, new Action(() => Apply(target)));
        }
        catch (Exception ex)
        {
            _logger.Warning(ex, "Queuing the focus request {Target} failed", target);
        }
    }

    private void Apply(FocusTarget target)
    {
        try
        {
            bool moved = _window.MoveFocusTo(target);
            _logger.Debug("Focus request {Target}: {Outcome}", target, moved ? "moved" : "no focusable element");
        }
        catch (Exception ex)
        {
            _logger.Warning(ex, "Applying the focus request {Target} failed", target);
        }
    }
}
